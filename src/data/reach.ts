export const REACH_TOWN_COUNT = REACH.reduce((n, p) => n + p.towns.length, 0);

export function placeLabel(place: ReachPlace) {
  const familiar = place.also?.[0];
  return familiar ? `${place.name} (${familiar})` : place.name;
}

export function placeHaystack(place: ReachPlace) {
  return [place.name, ...(place.also ?? [])].join(" ");
}
